"""
models/stance_inference_v2.py
=============================
Final stance inference pipeline (v2) implementing a heuristic Oppose detection layer.

HEURISTIC PIPELINE — READ THIS BEFORE USE
------------------------------------------
This module combines two independently trained models to produce a four-label stance
prediction (Support / Oppose / Neutral / Unclear). The **Oppose** label is NOT produced
by a validated Oppose classifier.  It is assigned by the following rule:

    1.  Run the Sentiment140 streaming sentiment model (negative / positive).
    2.  Run the TF-IDF stance model trained on AI-generated working labels
        (labels: Support / Neutral / Unclear).
    3.  Heuristic:
        - If sentiment == "negative" AND stance_raw != "Support"
          → final_stance = "Oppose"   (prediction_method = "heuristic_oppose")
        - Otherwise
          → final_stance = stance_raw  (prediction_method = "stance_model_direct")

Important caveats:
  * The stance model was trained ONLY on Support / Neutral / Unclear labels.
    It has never seen an Oppose example during training.
  * Oppose predictions are heuristic approximations based on tone; they are NOT
    validated classifier outputs and should NOT be presented as ground truth.
  * The sentiment model (Sentiment140) was trained on Twitter data, not consultation
    text; domain transfer may cause systematic misclassification.
  * All outputs carry an explicit disclaimer column to communicate these limitations
    to downstream consumers.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import numpy as np
import pandas as pd

# ── project-internal imports ────────────────────────────────────────────────
from models.new_comment_inference import ArtifactError, load_verified_pipeline
from models.sentiment_analysis.streaming_baseline import Sentiment140StreamingClassifier

# ── paths ────────────────────────────────────────────────────────────────────
ROOT = Path(__file__).resolve().parents[1]
STANCE_RUN = ROOT / "data" / "stance_training_ai_working_labels" / "run_pool400_ai_v1_3class"
SENTIMENT_MODEL_DIR = ROOT / "data" / "sentiment_training" / "sentiment140_hashing_sgd_v1"
SENTIMENT_MODEL_PATH = SENTIMENT_MODEL_DIR / "model.joblib"
SENTIMENT_MANIFEST_PATH = SENTIMENT_MODEL_DIR / "manifest.json"

# ── constants ────────────────────────────────────────────────────────────────
DEFAULT_MODEL = "linsvm"
MIN_CHARS = 3
SENTIMENT_MODEL_SOURCE = "sentiment140_hashing_sgd_v1"
OPPOSE_DISCLAIMER = (
    "HEURISTIC DISCLAIMER: 'Oppose' predictions are generated by a rule "
    "(negative sentiment from a Twitter-trained model AND non-Support stance from "
    "a model trained on Support/Neutral/Unclear AI-generated labels). "
    "Oppose is NOT produced by a validated Oppose classifier and must be treated "
    "as provisional. Support/Neutral/Unclear predictions are from the stance model "
    "directly and are also AI-working-label approximations, not human-verified stances."
)


def _sha256(p: Path) -> str:
    """Compute SHA-256 of a file in streaming chunks."""
    digest = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _load_verified_sentiment_model(
    model_path: Path = SENTIMENT_MODEL_PATH,
    manifest_path: Path = SENTIMENT_MANIFEST_PATH,
) -> Sentiment140StreamingClassifier:
    """
    Load the Sentiment140 streaming classifier after verifying its SHA-256 against
    the value recorded in manifest.json under ``outputs_sha256.model.joblib``.

    Raises
    ------
    ArtifactError
        If the manifest is missing, malformed, or the checksum does not match.
    """
    if not manifest_path.is_file():
        raise ArtifactError(f"Sentiment140 manifest not found at {manifest_path}")
    if not model_path.is_file():
        raise ArtifactError(f"Sentiment140 model.joblib not found at {model_path}")

    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ArtifactError(f"Cannot read sentiment manifest: {exc}") from exc

    declared_sha = (manifest.get("outputs_sha256") or {}).get("model.joblib")
    if not declared_sha:
        raise ArtifactError(
            "Sentiment140 manifest has no 'outputs_sha256.model.joblib' entry; "
            "refusing to load unverified artifact."
        )

    actual_sha = _sha256(model_path)
    if actual_sha != declared_sha:
        raise ArtifactError(
            f"SHA-256 mismatch for {model_path.name}: "
            f"expected {declared_sha}, got {actual_sha}"
        )

    return Sentiment140StreamingClassifier.load(model_path)


@dataclass
class FinalStancePredictor:
    """
    Heuristic four-label stance predictor for new consultation comments.

    Combines:
      - A TF-IDF stance pipeline (Support / Neutral / Unclear) trained on
        AI-generated working labels from ``run_pool400_ai_v1_3class``.
      - The Sentiment140 HashingVectorizer+SGD sentiment model (negative / positive).

    Oppose is assigned heuristically — see the module docstring for details.

    Parameters
    ----------
    model : {"linsvm", "logreg"}
        Which stance pipeline variant to load (default: "linsvm").
    """

    model: str = DEFAULT_MODEL
    stance_run: Path = field(default_factory=lambda: STANCE_RUN)
    sentiment_model_path: Path = field(default_factory=lambda: SENTIMENT_MODEL_PATH)
    sentiment_manifest_path: Path = field(default_factory=lambda: SENTIMENT_MANIFEST_PATH)

    def __post_init__(self) -> None:
        self.stance_pipe, self.stance_meta = load_verified_pipeline(
            self.stance_run, self.model
        )
        self.sentiment_clf = _load_verified_sentiment_model(
            self.sentiment_model_path, self.sentiment_manifest_path
        )

    # ── internal helpers ─────────────────────────────────────────────────────

    @staticmethod
    def _margin(pipe, texts: list[str]) -> np.ndarray:
        """Compute decision-function margin (gap between top-2 scores)."""
        dec = pipe.decision_function(texts)
        dec = dec.reshape(len(texts), -1)
        if dec.shape[1] == 1:          # binary / distance from hyperplane
            return np.abs(dec[:, 0])
        s = np.sort(dec, axis=1)
        return s[:, -1] - s[:, -2]    # top-1 minus top-2

    # ── public API ───────────────────────────────────────────────────────────

    def predict(self, texts: list[str]) -> pd.DataFrame:
        """
        Run the full heuristic stance pipeline on a list of raw text strings.

        Parameters
        ----------
        texts : list[str]
            Raw comment texts (None values are coerced to empty string).

        Returns
        -------
        pd.DataFrame
            One row per input text with columns:
            text, input_status, final_stance, stance_raw, stance_margin,
            sentiment_prediction, sentiment_model_source, prediction_method,
            stance_label_source, disclaimer
        """
        texts = ["" if t is None else str(t) for t in texts]
        valid_mask = np.array([len(t.strip()) >= MIN_CHARS for t in texts])

        # Initialise output frame
        out = pd.DataFrame({
            "text": texts,
            "input_status": np.where(valid_mask, "ok", "too_short_or_empty"),
        })
        for col in (
            "final_stance", "stance_raw", "stance_margin",
            "sentiment_prediction", "sentiment_model_source",
            "prediction_method", "stance_label_source",
        ):
            out[col] = None

        out["disclaimer"] = OPPOSE_DISCLAIMER

        valid_texts = [t for t, ok in zip(texts, valid_mask) if ok]
        if not valid_texts:
            return out

        # ── step 1: sentiment ─────────────────────────────────────────────
        sentiment_preds = self.sentiment_clf.predict(valid_texts)   # ndarray of str

        # ── step 2: stance ────────────────────────────────────────────────
        stance_preds = self.stance_pipe.predict(valid_texts)        # ndarray of str
        stance_margins = np.round(self._margin(self.stance_pipe, valid_texts), 4)

        # ── step 3: heuristic Oppose ──────────────────────────────────────
        final_stances: list[Optional[str]] = []
        methods: list[str] = []
        label_sources: list[str] = []

        for sent, stance in zip(sentiment_preds, stance_preds):
            if sent == "negative" and stance != "Support":
                final_stances.append("Oppose")
                methods.append("heuristic_oppose")
                label_sources.append("heuristic_oppose_unverified")
            else:
                final_stances.append(str(stance))
                methods.append("stance_model_direct")
                label_sources.append("ai_working_label_unverified")

        # ── write results back to the dataframe ───────────────────────────
        out.loc[valid_mask, "sentiment_prediction"] = sentiment_preds
        out.loc[valid_mask, "sentiment_model_source"] = SENTIMENT_MODEL_SOURCE
        out.loc[valid_mask, "stance_raw"] = stance_preds
        out.loc[valid_mask, "stance_margin"] = stance_margins
        out.loc[valid_mask, "final_stance"] = final_stances
        out.loc[valid_mask, "prediction_method"] = methods
        out.loc[valid_mask, "stance_label_source"] = label_sources

        return out
